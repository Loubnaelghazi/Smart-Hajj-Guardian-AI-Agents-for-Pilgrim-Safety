String translate(String value, String language) {
  if (language != 'ar') return value;
  final exact = arabic[value];
  if (exact != null) return exact;
  if (value.startsWith('Hello, ')) return 'مرحباً، ${value.substring(7)}';
  if (value.contains('\n')) {
    return value.split('\n').map((s) => translate(s, language)).join('\n');
  }
  for (final separator in [' • ', ' · ', ', ']) {
    if (value.contains(separator)) {
      return value
          .split(separator)
          .map((s) => translate(s, language))
          .join(separator);
    }
  }
  final minutes = RegExp(r'^(\d+) minutes ago$').firstMatch(value);
  if (minutes != null) return 'منذ ${minutes[1]} دقيقة';
  final seconds = RegExp(r'^(\d+|\?)s ago$').firstMatch(value);
  if (seconds != null) return 'منذ ${seconds[1]} ثانية';
  if (value.startsWith('Server received ')) {
    return 'استلم الخادم ${value.substring(16)}';
  }
  if (value.endsWith(' m to meeting point')) {
    return '${value.substring(0, value.length - 19)} متر إلى نقطة التجمّع';
  }
  if (value.endsWith(' seconds')) {
    return '${value.substring(0, value.length - 8)} ثانية';
  }
  if (value.endsWith(' m')) {
    return '${value.substring(0, value.length - 2)} متر';
  }
  return value;
}
